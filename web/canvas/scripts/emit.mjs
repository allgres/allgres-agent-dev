// Turns Vite's single-file build into web/canvas.html, the file src/lib.rs
// embeds with include_str!. The server answers /canvas with a per-response
// nonce and `script-src 'nonce-…'; style-src 'nonce-…'`, so every inline
// <script> and <style> must carry the placeholder it replaces. Fails the
// build if anything would still load from outside the document.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
let html = readFileSync(here('../dist/index.html'), 'utf8');

// Walk the document tag by tag and skip over each element's body: bundled
// JavaScript legitimately contains strings such as "<script><\/script>",
// and a blind regex over the whole file would rewrite them.
let out = '';
let tags = 0;
let i = 0;
const open = /<(script|style|link)\b[^>]*>/gi;
for (let m; (m = open.exec(html)); ) {
  const [tag, name] = m;
  if (/\b(src|href)=/i.test(tag)) {
    console.error('canvas build references an external resource:', tag);
    process.exit(1);
  }
  const stamped = /\bnonce=/.test(tag) ? tag : tag.replace(/^<(\w+)/, '<$1 nonce="__CSP_NONCE__"');
  const close = html.toLowerCase().indexOf(`</${name.toLowerCase()}>`, m.index + tag.length);
  if (close < 0) {
    console.error(`unterminated <${name}> in canvas build`);
    process.exit(1);
  }
  out += html.slice(i, m.index) + stamped + html.slice(m.index + tag.length, close);
  i = close;
  open.lastIndex = close;
  tags++;
}
html = out + html.slice(i);
if (tags === 0) {
  console.error('canvas build produced no inline script or style');
  process.exit(1);
}

const banner = '<!-- Generated by web/canvas (npm run build). Do not edit by hand. -->\n';
writeFileSync(here('../../canvas.html'), banner + html);
console.log(`wrote web/canvas.html (${(html.length / 1024).toFixed(0)} KiB, ${tags} inline tags)`);
